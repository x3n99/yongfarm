create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  nama text not null default '',
  username text unique,
  created_at timestamptz not null default now()
);

create table if not exists public.produk (
  id_produk bigint generated by default as identity primary key,
  nama varchar(100) not null unique,
  deskripsi text,
  image varchar(255)
);

create table if not exists public.harga (
  id_harga bigint generated by default as identity primary key,
  produk varchar(100) not null references public.produk (nama),
  harga numeric(14, 2) not null check (harga >= 0),
  tanggal_berlaku date not null
);

create table if not exists public.produksi (
  id_produksi bigint generated by default as identity primary key,
  tanggal date not null,
  jumlah_butir integer not null check (jumlah_butir >= 0),
  jumlah_kg numeric(10, 2) not null check (jumlah_kg >= 0),
  pakan_kg numeric(10, 2) not null check (pakan_kg >= 0),
  kondisi_ayam varchar(255),
  created_at timestamptz not null default now()
);

create table if not exists public.penjualan (
  id_penjualan bigint generated by default as identity primary key,
  tanggal date not null,
  nama_pembeli varchar(150) not null,
  produk varchar(100) not null references public.produk (nama),
  jumlah_unit integer not null default 0 check (jumlah_unit >= 0),
  satuan varchar(50) not null default 'butir'
    check (satuan in ('butir', 'pack_10', 'pack_12', 'tray', 'crate')),
  jumlah_butir integer not null default 0 check (jumlah_butir >= 0),
  jumlah_kg numeric(10, 2) not null check (jumlah_kg >= 0),
  harga_per_unit numeric(14, 2) not null default 0 check (harga_per_unit >= 0),
  harga_unit varchar(50) not null default 'butir',
  harga_per_butir numeric(14, 2) not null default 0 check (harga_per_butir >= 0),
  harga_per_kg numeric(14, 2) not null default 0 check (harga_per_kg >= 0),
  total_harga numeric(14, 2) not null check (total_harga >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.pesanan (
  id bigint generated by default as identity primary key,
  nama varchar(150) not null,
  no_hp varchar(50) not null,
  alamat text not null,
  produk varchar(100) not null references public.produk (nama),
  satuan varchar(50) not null default 'butir'
    check (satuan in ('butir', 'pack_10', 'pack_12', 'tray', 'crate')),
  jumlah integer not null check (jumlah > 0),
  pesan text,
  status varchar(50) not null default 'Pending'
    check (status in ('Pending', 'Processing', 'Completed')),
  created_at timestamptz not null default now()
);

create index if not exists harga_produk_tanggal_idx
  on public.harga (produk, tanggal_berlaku desc);
create index if not exists produksi_tanggal_idx on public.produksi (tanggal desc);
create index if not exists penjualan_tanggal_idx on public.penjualan (tanggal desc);
create index if not exists pesanan_created_at_idx on public.pesanan (created_at desc);

create or replace function public.is_yongfarm_admin()
returns boolean
language sql
stable
security invoker
set search_path = ''
as $$
  select coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '') = 'admin';
$$;

alter table public.profiles enable row level security;
alter table public.produk enable row level security;
alter table public.harga enable row level security;
alter table public.produksi enable row level security;
alter table public.penjualan enable row level security;
alter table public.pesanan enable row level security;

create policy "Profiles are visible to their owner or admins"
  on public.profiles for select to authenticated
  using (id = (select auth.uid()) or (select public.is_yongfarm_admin()));

create policy "Products are publicly readable"
  on public.produk for select to anon, authenticated using (true);
create policy "Admins manage products"
  on public.produk for all to authenticated
  using ((select public.is_yongfarm_admin()))
  with check ((select public.is_yongfarm_admin()));

create policy "Prices are publicly readable"
  on public.harga for select to anon, authenticated using (true);
create policy "Admins manage prices"
  on public.harga for all to authenticated
  using ((select public.is_yongfarm_admin()))
  with check ((select public.is_yongfarm_admin()));

create policy "Admins manage production"
  on public.produksi for all to authenticated
  using ((select public.is_yongfarm_admin()))
  with check ((select public.is_yongfarm_admin()));

create policy "Admins manage sales"
  on public.penjualan for all to authenticated
  using ((select public.is_yongfarm_admin()))
  with check ((select public.is_yongfarm_admin()));

create policy "Public can submit pending orders"
  on public.pesanan for insert to anon, authenticated
  with check (status = 'Pending');
create policy "Admins manage orders"
  on public.pesanan for all to authenticated
  using ((select public.is_yongfarm_admin()))
  with check ((select public.is_yongfarm_admin()));

grant select on public.produk, public.harga to anon, authenticated;
grant insert on public.pesanan to anon, authenticated;
grant select, insert, update, delete on public.profiles, public.produk, public.harga,
  public.produksi, public.penjualan, public.pesanan to authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant usage on sequence public.pesanan_id_seq to anon;
